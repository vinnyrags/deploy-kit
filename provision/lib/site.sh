# shellcheck shell=bash
# deploy-kit — what new-site.sh builds for one environment, as functions the tests can
# run without MariaDB or systemd. Sourced by provision/new-site.sh and the tests; needs
# provision/lib/migrate.sh (vhost_to_releases) sourced alongside.
#
# Every new site is born on the layout vincentragosta.io was migrated to: releases under
# /srv/<host>/ (root-owned, read-only to PHP), mutable state in shared/, and each
# environment's PHP running as its own user. The in-place layout stays supported for the
# sites already on it; new-site.sh no longer creates it.

# site_pool_users <slug suffix> [base] -> "<prod user> <staging user>"
#   Linux user names stop at 32 characters; leave room for "-stg".
site_pool_users() {
  local base="${2:-$1}"
  base="${base:0:28}"
  printf '%s %s\n' "$base" "${base}-stg"
}

# site_init_base <base> <pool user>
#   <base>/{releases,shared} for a site with nothing to copy from. shared/ holds what PHP
#   may write (uploads, debug.log); the env file is written by the caller and locked to
#   640 root:<user>. Refuses an existing <base>: never adopt a directory it did not make.
site_init_base() {
  local base="$1" user="$2"
  [ -e "$base" ] && { echo "REFUSING: $base already exists" >&2; return 1; }
  mkdir -p "$base/releases" "$base/shared/wp-content/uploads"
  : > "$base/shared/wp-content/debug.log"
  chown root:root "$base" "$base/releases" "$base/shared" "$base/shared/wp-content"
  chmod 755 "$base" "$base/releases" "$base/shared" "$base/shared/wp-content"
  chown -R "${user}:${user}" "$base/shared/wp-content/uploads" "$base/shared/wp-content/debug.log"
}

# site_conf <theme> <php_ver> <prod base> <staging base> <zone dir> <prod user> <staging user>
#   The /etc/deploy-kit/<slug>.conf a new site starts with.
site_conf() {
  local theme="$1" php="$2" prod="$3" stg="$4" zone="$5" pu="$6" su="$7"
  cat <<CONF
# Written by provision/new-site.sh. config/site.conf.example documents every key.
PROFILE=mythus-ix
THEME=${theme}
PHP_VER=${php}
FPM_ACTION=reload
REDIS=0
declare -A DEPLOY_DIR=( [main]=${prod}/current [develop]=${stg}/current )
declare -A ENV_NAME=( [main]=production [develop]=staging )
declare -A CACHE_DIR=( [main]=/var/cache/nginx/${zone} [develop]=/var/cache/nginx/${zone}-staging )
declare -A LAYOUT=( [main]=releases [develop]=releases )
declare -A POOL_USER=( [main]=${pu} [develop]=${su} )
BACKUP_BRANCH=main
CONF
}

# site_vhost <template> <server names> <base> <php_ver> <site suffix> <cache zone>
#   The port-80 vhost, rooted at <base>/current with $realpath_root for PHP, so a release
#   switch takes effect atomically (see vhost_to_releases). Prints the file.
site_vhost() {
  local tpl="$1" names="$2" base="$3" php="$4" site="$5" zone="$6" tmp
  tmp="$(mktemp)"
  sed -e "s#{{SITE}}#${site}#g" -e "s#{{PHP_VER}}#${php}#g" -e "s#{{SERVER_NAMES}}#${names}#g" \
      -e "s#{{WEBROOT}}#${base}/current#g" -e "s#{{CACHE_ZONE}}#${zone}#g" "$tpl" > "$tmp"
  vhost_to_releases "$tmp" "${base}/current" "${base}/current" >/dev/null || { rm -f "$tmp"; return 1; }
  cat "$tmp"; rm -f "$tmp"
}

# site_salts -> eight define() lines with fresh random values. Hex keeps them free of
# quotes and backslashes; 32 random bytes each.
site_salts() {
  local k
  printf '\n// Salts: generated by new-site.sh for this site and environment only.\n'
  for k in AUTH_KEY SECURE_AUTH_KEY LOGGED_IN_KEY NONCE_KEY AUTH_SALT SECURE_AUTH_SALT LOGGED_IN_SALT NONCE_SALT; do
    printf "define( '%s', '%s' );\n" "$k" "$(openssl rand -hex 32)"
  done
}
